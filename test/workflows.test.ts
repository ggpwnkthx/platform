import { describe, expect, test } from 'bun:test'
import { readdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { parseAllDocuments } from 'yaml'
import { readEnv } from '../packages/access/src/runtime/env'

/**
 * The workflows of the platform.
 *
 * There was one set of workflows per repository before the merge. There
 * is one set now, and these are the checks that keep it honest.
 *
 * The first check is about the outputs: the steps of a job read the
 * outputs of the other steps with `steps.<id>.outputs.<name>`, and the
 * jobs read the outputs of the other jobs with
 * `needs.<job>.outputs.<name>`. An output that is written by a step
 * that has **no id** is not readable: the expression is empty, and the
 * step that reads it fails long after the mistake was made.
 *
 * The second check is about the environment of the access service: the
 * workflows of the platform start the service of a **production**
 * deployment, and a production deployment refuses to start with a secret
 * that is too short or that is the value of the example. A workflow
 * that names a secret the service refuses is a workflow that fails in
 * the middle of a release.
 *
 * The third check is about the release: a tag that is pushed with the
 * token of the workflow does not start a workflow by itself, so the
 * release is **dispatched**. A workflow that cannot be dispatched is a
 * release that never starts.
 */
const root = join(import.meta.dir, '..')
const WORKFLOWS = join(root, '.github', 'workflows')

/** The workflows that publish a release. */
const RELEASES = ['release.yml', 'release-binaries.yml']

/** The placeholders of the values that a workflow computes. */
const PLACEHOLDERS: Record<string, string> = {
  // The key of the signing is generated by the workflow: the value of a
  // placeholder is a PEM, and that is all the service reads of it.
  ACCESS_SIGNING_KEY: '-----BEGIN PRIVATE KEY-----\nMIIB\n-----END PRIVATE KEY-----',
  ACCESS_PREVIOUS_SIGNING_KEY: '-----BEGIN PRIVATE KEY-----\nMIIB\n-----END PRIVATE KEY-----',
}

/** A step of a workflow, in the shape the check needs. */
interface Step {
  id?: string
  name?: string
  uses?: string
  run?: string
  with?: Record<string, unknown>
}

/** The outputs a step writes to the environment of the runner. */
function outputsOf(step: Step): string[] {
  if (!step.run) return []
  const names = new Set<string>()
  // `echo "name=value" >> "$GITHUB_OUTPUT"` and its variants.
  for (const match of step.run.matchAll(
    /echo\s+"?([A-Za-z0-9_-]+)=[^"]*"?\s*>>\s*"?\$GITHUB_OUTPUT"?/g
  )) {
    names.add(match[1]!)
  }
  return [...names]
}

/** Every string of a value, wherever it is. */
function stringsOf(value: unknown): string[] {
  if (typeof value === 'string') return [value]
  if (Array.isArray(value)) return value.flatMap(stringsOf)
  if (value && typeof value === 'object') {
    return Object.values(value as Record<string, unknown>).flatMap(stringsOf)
  }
  return []
}

/**
 * The value of a workflow.
 *
 * A value that the workflow computes is not read here: the ones that
 * are a repetition and a file are, and the others are skipped.
 */
function valueOfWorkflow(raw: string): string | null {
  const value = raw.trim().replace(/^["']|["']$/g, '')
  const repetition = /^\$\(printf '(.+?)%\.0s' \{1\.\.(\d+)\}\)$/.exec(value)
  if (repetition) return repetition[1]!.repeat(Number(repetition[2]))
  if (value.includes('$(')) return null
  return value
}

/** The environment of a workflow: the variables of the service it names. */
async function environmentOf(file: string): Promise<Record<string, string>> {
  const content = await readFile(file, 'utf8')
  const environment: Record<string, string> = {}
  const lines = content.split('\n')
  for (const line of lines) {
    // The flag of a container: `-e ACCESS_ADMIN_TOKEN=the-token`. The value
    // is quoted when it holds a space.
    const flag = /-e (ACCESS_[A-Z_]+)=("[^"]*"|'[^']*'|\S+)/.exec(line)
    if (flag) {
      const value = valueOfWorkflow(flag[2]!)
      if (value !== null) environment[flag[1]!] = value
      continue
    }
    // The block of an environment: `ACCESS_ADMIN_TOKEN: the-token`.
    const entry = /^\s+(ACCESS_[A-Z_]+):\s+(.+)$/.exec(line)
    if (entry) {
      const value = valueOfWorkflow(entry[2]!)
      if (value !== null) environment[entry[1]!] = value
    }
  }
  return environment
}

describe('the outputs of the workflows', () => {
  test('the outputs the steps read are the outputs the steps write', async () => {
    const files = (await readdir(WORKFLOWS)).filter((name) => name.endsWith('.yml'))
    expect(files.length).toBeGreaterThan(0)

    const findings: string[] = []
    for (const file of files) {
      const text = await readFile(join(WORKFLOWS, file), 'utf8')
      const docs = parseAllDocuments(text)
      expect(docs[0]?.errors).toEqual([])
      const workflow = docs[0]!.toJS() as {
        jobs: Record<string, { steps?: Step[] }>
      }

      for (const [jobName, job] of Object.entries(workflow.jobs ?? {})) {
        const steps = job.steps ?? []
        const ids = new Set(steps.map((step) => step.id).filter(Boolean) as string[])
        const written = new Map<string, string[]>()
        for (const step of steps) {
          if (!step.id) continue
          written.set(step.id, outputsOf(step))
        }

        for (const step of steps) {
          const texts = [step.run ?? '', ...stringsOf(step.with)]
          for (const text of texts) {
            // steps.<id>.outputs.<name>
            for (const match of text.matchAll(
              /steps\.([A-Za-z0-9_-]+)\.outputs\.([A-Za-z0-9_-]+)/g
            )) {
              const [, id, name] = match
              if (!ids.has(id!)) {
                findings.push(
                  `${file}: the job ${jobName} reads steps.${id}.outputs.${name} and no step of the job has the id ${id}`
                )
                continue
              }
              const names = written.get(id!) ?? []
              if (!names.includes(name!)) {
                findings.push(
                  `${file}: the job ${jobName} reads steps.${id}.outputs.${name} and the step ${id} writes ${
                    names.length ? names.join(', ') : 'nothing'
                  }`
                )
              }
            }
          }
        }
      }
    }
    expect(findings).toEqual([])
  })

  test('the outputs the jobs read are the outputs the jobs declare', async () => {
    const files = (await readdir(WORKFLOWS)).filter((name) => name.endsWith('.yml'))
    const findings: string[] = []

    for (const file of files) {
      const text = await readFile(join(WORKFLOWS, file), 'utf8')
      const workflow = parseAllDocuments(text)[0]!.toJS() as {
        jobs: Record<string, { outputs?: Record<string, unknown>; steps?: Step[] }>
      }
      const jobs = workflow.jobs ?? {}

      for (const [jobName, job] of Object.entries(jobs)) {
        for (const step of job.steps ?? []) {
          const texts = [step.run ?? '', ...stringsOf(step.with)]
          for (const text of texts) {
            // needs.<job>.outputs.<name>
            for (const match of text.matchAll(
              /needs\.([A-Za-z0-9_-]+)\.outputs\.([A-Za-z0-9_-]+)/g
            )) {
              const [, needed, name] = match
              const target = jobs[needed!]
              if (!target) {
                findings.push(
                  `${file}: the job ${jobName} reads needs.${needed}.outputs.${name} and no job has that name`
                )
                continue
              }
              const declared = target.outputs ?? {}
              if (!Object.keys(declared).includes(name!)) {
                findings.push(
                  `${file}: the job ${jobName} reads needs.${needed}.outputs.${name} and the job ${needed} declares ${
                    Object.keys(declared).join(', ') || 'nothing'
                  }`
                )
              }
            }
          }
        }
      }
    }
    expect(findings).toEqual([])
  })
})

describe('the environment of the workflows', () => {
  test('the service of a production deployment starts with it', async () => {
    const files = (await readdir(WORKFLOWS)).filter((name) => name.endsWith('.yml'))
    expect(files.length).toBeGreaterThan(0)

    const findings: string[] = []
    for (const name of files) {
      const environment = await environmentOf(join(WORKFLOWS, name))
      // The workflows that do not start the service do not have to name
      // a secret: the ones that do are the ones this test holds.
      if (!environment.ACCESS_ADMIN_TOKEN && !environment.ACCESS_ADMIN_TOKENS) continue

      const withPlaceholders = { ...environment }
      for (const [name, value] of Object.entries(PLACEHOLDERS)) {
        if (!withPlaceholders[name]) withPlaceholders[name] = value
      }

      let message = ''
      try {
        readEnv({ ACCESS_ENVIRONMENT: 'production', ...withPlaceholders })
      } catch (error) {
        message = String(error)
      }
      if (message !== '') {
        findings.push(`${name}: ${message}`)
      }
    }
    expect(findings).toEqual([])
  })
})

describe('the release of the workflows', () => {
  /**
   * The block of a trigger of a workflow.
   *
   * The block of a trigger is what follows its name, until the next key
   * of the workflow: the triggers of a workflow are the keys of `on:`,
   * and the block of one of them is what it holds.
   */
  function triggerOf(content: string, name: string): string {
    const lines = content.split('\n')
    const start = lines.findIndex((line) => line.trim() === `${name}:`)
    if (start < 0) return ''
    const rest = lines.slice(start + 1)
    const end = rest.findIndex((line) => /^[a-z]/.test(line))
    return (end < 0 ? rest : rest.slice(0, end)).join('\n')
  }

  test('a release can be dispatched with the tag it publishes', async () => {
    // The push of the tag by the workflow of the tag carries the token
    // of the workflow, and GitHub does not start a workflow on a push
    // that carries it. The release is dispatched instead: a workflow
    // that cannot be dispatched is a release that never starts.
    const findings: string[] = []
    for (const name of RELEASES) {
      const content = await readFile(join(WORKFLOWS, name), 'utf8')
      const dispatch = triggerOf(content, 'workflow_dispatch')
      if (dispatch === '') {
        findings.push(`${name}: it cannot be dispatched`)
        continue
      }
      // The dispatch asks for the tag: the release is the tag.
      if (!/^\s*tag:\s*$/m.test(dispatch) || !dispatch.includes('required: true')) {
        findings.push(`${name}: the dispatch does not ask for a tag`)
      }
      // The tag of the dispatch is the one that is released: the
      // checkout and the version are read from it.
      if (!content.includes('github.event.inputs.tag')) {
        findings.push(`${name}: the dispatch does not read the tag it is given`)
      }
    }
    expect(findings).toEqual([])
  })

  test('the workflow of the tag dispatches the release', async () => {
    // The tag is pushed by the workflow of the tag: nothing starts on
    // that push, and the workflow dispatches the release itself.
    const content = await readFile(join(WORKFLOWS, 'tag.yml'), 'utf8')
    const findings: string[] = []
    // The dispatch needs the permission to dispatch a workflow.
    if (!/permissions:[\s\S]*?actions: write/.test(content)) {
      findings.push('tag.yml: it may not dispatch a workflow')
    }
    // The dispatch is the way the release starts: the workflow runs the
    // workflows of the release, and it names them.
    if (!content.includes('gh workflow run')) {
      findings.push('tag.yml: it dispatches nothing')
    }
    for (const name of RELEASES) {
      if (!content.includes(name)) {
        findings.push(`tag.yml: it does not dispatch ${name}`)
      }
    }
    expect(findings).toEqual([])
  })
})
